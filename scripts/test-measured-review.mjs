import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {parseCase} from '../products/dd84-desktop/troubleshooting.mjs';

// Synthetic, local-only exports: exercise user input, persistence and validation.
export async function testMeasuredReview({browser,origin,output,ok}) {
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const file=(name,text)=>({name,mimeType:'text/csv',buffer:Buffer.from(text)});
  const csv=rows=>'HP Tuners CSV Log File\nVersion: 1.0\n[Channel Information]\n0,1,2,3\nOffset,RPM,MAP,Spark\ns,rpm,kPa,deg\n[Channel Data]\n'+rows;
  await page.goto(origin+'/studio/');
  await page.locator('#workspace-navigation [data-page=troubleshoot]').click();
  await page.getByText('3. Compare measured differences and record the outcome',{exact:true}).click();
  const panel=page.locator('section.measured-review'),status=panel.getByRole('status');
  await page.getByLabel('Earlier CSV',{exact:true}).setInputFiles(file('earlier.csv',csv('0,1000,50,10\n1,2000,60,20\n2,3000,70,30')));
  await status.filter({hasText:'Recording loaded locally'}).waitFor();
  await page.getByLabel('Later CSV',{exact:true}).setInputFiles(file('later.csv',csv('0,1000,50,12\n1,2000,60,16\n2,3000,70,32')));
  await status.filter({hasText:'Recording loaded locally'}).waitFor();
  await page.getByLabel('Earlier filter 1',{exact:true}).selectOption('1');
  await page.getByLabel('Earlier filter 1 minimum',{exact:true}).fill('1000');
  await page.getByLabel('Earlier filter 1 maximum',{exact:true}).fill('2000');
  await page.getByLabel('Later filter 1',{exact:true}).selectOption('1');
  await page.getByLabel('Later filter 1 minimum',{exact:true}).fill('1000');
  await page.getByLabel('Later filter 1 maximum',{exact:true}).fill('2000');
  await page.getByLabel('Reported outcome',{exact:true}).selectOption('worse');
  await page.getByLabel('What did you observe, and what supports it?',{exact:true}).fill('Synthetic observation only; no actual vehicle tested.');
  await page.getByRole('button',{name:'Save troubleshooting case',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Build and attach the measured review or discard'}).waitFor();
  await page.getByRole('button',{name:'Build and attach measured review',exact:true}).click();
  await status.filter({hasText:'Measured review attached locally'}).waitFor();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Save troubleshooting case',exact:true}).click();
  const saved=JSON.parse(await fs.readFile(await(await download).path(),'utf8')),r=saved.measuredReview;
  assert.equal(saved.format,'DD84_TROUBLESHOOTING_CASE_V2');assert.equal(r.before.rows,2);assert.equal(r.after.rows,2);assert.equal(r.before.outsideFilterRows,1);
  assert.equal(r.comparisons.find(c=>c.name==='Spark').delta.mean,-1);assert.equal(r.outcome.result,'worse');assert.equal(r.learningReady,false);assert.equal(r.before.tune,null);
  assert.equal(saved.assessment.status,'CONCERNS_RECORDED');parseCase(JSON.stringify(saved));
  ok('measured review filters real-shaped CSV rows, calculates signed deltas, and blocks saving pending edits');
  await page.getByLabel('Later CSV',{exact:true}).setInputFiles(file('bad.csv','invalid'));
  await status.filter({hasText:'Previous loaded recording'}).waitFor();
  await page.getByRole('button',{name:'Build and attach measured review',exact:true}).click();await status.filter({hasText:'Measured review attached locally'}).waitFor();
  const second=page.waitForEvent('download');await page.getByRole('button',{name:'Save troubleshooting case',exact:true}).click();
  assert.deepEqual(JSON.parse(await fs.readFile(await(await second).path(),'utf8')).measuredReview,r);
  await page.locator('#trouble-open').setInputFiles(file('saved.json',JSON.stringify(saved)));
  await page.getByRole('button',{name:'Replace current case',exact:true}).click();
  await status.filter({hasText:'Saved measurement summary restored'}).waitFor();
  await page.getByLabel('What did you observe, and what supports it?',{exact:true}).fill('Pending change');
  await page.getByRole('button',{name:'Discard pending measured changes',exact:true}).click();
  assert.equal(await page.getByLabel('What did you observe, and what supports it?',{exact:true}).inputValue(),r.outcome.observation);
  await page.setViewportSize({width:700,height:600});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await panel.getByRole('heading',{name:'Measured differences and recorded outcome'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(output,'studio-measured-review.png')});
  assert.deepEqual(errors,[]);await page.close();
  ok('bad CSV retains prior data; reopening and discarding pending notes preserve the attached review');
  const web=await browser.newPage({viewport:{width:390,height:844}});let transmissions=0;
  await web.route('**/api/v1/**',route=>{transmissions++;return route.fulfill({status:401,json:{message:'Synthetic sign-in required'}});});
  await web.goto(origin+'/troubleshoot');const before=transmissions;
  await web.locator('#trouble-open').setInputFiles(file('measured.json',JSON.stringify(saved)));
  await web.getByRole('heading',{name:'Measured differences and recorded outcome'}).waitFor();
  assert(await web.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  const third=web.waitForEvent('download');await web.getByRole('button',{name:'Save troubleshooting case',exact:true}).click();
  assert.deepEqual(JSON.parse(await fs.readFile(await(await third).path(),'utf8')),saved);assert.equal(transmissions,before);
  await web.getByRole('heading',{name:'Measured differences and recorded outcome'}).scrollIntoViewIfNeeded();await web.screenshot({path:path.join(output,'web-measured-review-mobile.png')});await web.close();
  ok('desktop V2 review round-trips on mobile web without uploading local evidence');
  return saved;
}
